char *getcwd(char *buf, size_t size)
{
	if (!buf)
		return strdup(g_cwd);
	if (size > 0)
	{
		strncpy(buf, g_cwd, size - 1);
		buf[size - 1] = '\0';
		return buf;
	}
	return NULL;
}

int chdir(const char *path)
{
	if (!path || !*path)
		return -1;

	if (path[0] == '/')
	{
		strncpy(g_cwd, path, sizeof(g_cwd) - 1);
		g_cwd[sizeof(g_cwd) - 1] = '\0';
	}
	else
	{
		char temp[512];
		snprintf(temp, sizeof(temp), "%s/%s", g_cwd, path);
		strncpy(g_cwd, temp, sizeof(g_cwd) - 1);
		g_cwd[sizeof(g_cwd) - 1] = '\0';
	}

	size_t len = strlen(g_cwd);
	while (len > 1 && g_cwd[len - 1] == '/')
	{
		g_cwd[len - 1] = '\0';
		len--;
	}

	return 0;
}

