/*
 * How much of the stock 64 MiB scratch buffer the core heap may use.
 *
 * The GB300 field logs show 58 MiB heaps booting and running repeatedly
 * without firmware interference (the stock OS does not touch the scratch
 * buffer while a core owns it), while 52 MiB put OpenClaw's level-load
 * transients right against the ceiling (sbrk OOM at used=53184 KB). Keep a
 * 6 MiB reserve on GB300; SF2000 stays at the long-tested 60 MiB.
 */
#if defined(SF2000)
	#define SF2000_HEAP_LIMIT 0x03C00000u   /* 60 MiB of 64 MiB */
#else
	#define SF2000_HEAP_LIMIT 0x03A00000u   /* 58 MiB of 64 MiB */
#endif

extern int g_errno;

extern void (*__xlog)(const char *fmt, ...);
// #define __xlog(...)

void *sbrk(ptrdiff_t incr)
{
	static void *s_heap_end;
	static void *s_heap_ptr = NULL;
	if (!s_heap_ptr)
	{
		s_heap_ptr = gp_buf_64m;	// use stock's 64MB scratch buffer
		/*
		 * The scratch buffer is 64 MiB (0x4000000). Leave headroom for the
		 * firmware and the OS, which share it, and hand the rest to the core.
		 * This was 52 MiB (0x3400000); raised to 58 MiB for a little more room.
		 * Keep this below 0x4000000: __wrap_free() validates pointers against
		 * heap_beg + 0x4000000, so going past it would be rejected as foreign.
		 */
		s_heap_end = (void*)((char*)gp_buf_64m + SF2000_HEAP_LIMIT);
		xlog("sbrk init: heap_base=%p heap_end=%p (%u MiB)\n",
			s_heap_ptr, s_heap_end, (unsigned)(SF2000_HEAP_LIMIT >> 20));
	}

	void *curr_ptr = s_heap_ptr;
	void *new_ptr = (void*)((char*)s_heap_ptr + incr);

	if (new_ptr > s_heap_end || new_ptr < gp_buf_64m)
	{
		unsigned ra;
		asm volatile ("move %0, $ra" : "=r" (ra));
		xlog("sbrk OOM: curr=%p incr=%d end=%p used=%u KB ra=0x%08x\n",
			curr_ptr, (int)incr, s_heap_end, (unsigned)(((char*)curr_ptr - (char*)gp_buf_64m) / 1024), ra);
		lcd_bsod("sbrk OOM:\nincr=%d used=%u KB\nra=0x%08x",
			(int)incr, (unsigned)(((char*)curr_ptr - (char*)gp_buf_64m) / 1024), ra);
		return (void*)-1;
	}

	s_heap_ptr = new_ptr;

	if (incr >= 512 * 1024 || incr <= -512 * 1024) {
		unsigned ra;
		asm volatile ("move %0, $ra" : "=r" (ra));
		xlog("sbrk big: incr=%d used=%u KB ra=0x%08x\n", (int)incr, (unsigned)(((char*)s_heap_ptr - (char*)gp_buf_64m) / 1024), ra);
	}

	return curr_ptr;
}

// free() tracer. The emulator aborted inside newlib's _free_r with an address
// error, which means free() received either a misaligned pointer or one that
// never came from malloc (leaving _free_r to chase a garbage chunk header).
// Log such calls together with the caller's return address so the offending
// code can be identified from the log. The link uses --wrap=free.
void __real_free(void *ptr) __attribute__((weak));

__attribute__((noinline)) void __wrap_free(void *ptr)
{
	if (ptr)
	{
		unsigned long p = (unsigned long)ptr;
		unsigned long heap_beg = (unsigned long)gp_buf_64m;
		unsigned long heap_end = heap_beg + 0x4000000;

		if (((p & 7) != 0) || (p < heap_beg) || (p >= heap_end))
		{
			unsigned ra;
			asm volatile ("move %0, $ra" : "=r" (ra));

			unsigned size_word = 0;
			if ((p & 3) == 0)
				size_word = *(volatile unsigned *)(p - 4);

			xlog("[FREE-TRACE] invalid ptr=%p ra=%p size=0x%08X heap=[%p,%p)\n",
				ptr, (void *)ra, size_word, (void *)heap_beg, (void *)heap_end);
		}
	}

	__real_free(ptr);
}

static char g_cwd[512] = "/mnt/sda1";

static const char *resolve_path(const char *in, char *out, size_t out_size)
{
	if (!in || !*in)
		return in;

	char clean[512];
	size_t i = 0;
	while (in[i] && i < sizeof(clean) - 1)
	{
		clean[i] = (in[i] == '\\') ? '/' : in[i];
		i++;
	}
	clean[i] = '\0';

	const char *rel = clean;
	if (rel[0] == '/')
	{
		strncpy(out, rel, out_size - 1);
		out[out_size - 1] = '\0';
		return out;
	}

	while (rel[0] == '.' && rel[1] == '/')
		rel += 2;

	if ((rel[0] == '.' && rel[1] == '\0') || rel[0] == '\0')
		return g_cwd;

	snprintf(out, out_size, "%s/%s", g_cwd, rel);
	return out;
}

int open(const char *path, int flags, ...)
{
	char resolved[512];
	const char *p = resolve_path(path, resolved, sizeof(resolved));

	int fs_flags = 0;
	int fs_perms = 0666;    // all access?
	
	if (flags & O_RDONLY) fs_flags |= FS_O_RDONLY;
	if (flags & O_WRONLY) fs_flags |= FS_O_WRONLY;
	if (flags & O_RDWR)   fs_flags |= FS_O_RDWR;
	if (flags & O_APPEND) fs_flags |= FS_O_APPEND;
	if (flags & O_CREAT)  fs_flags |= FS_O_CREAT;
	if (flags & O_TRUNC)  fs_flags |= FS_O_TRUNC;

	int ret = fs_open(p, fs_flags, fs_perms);
	if (ret < 0) {
		errno = g_errno ? g_errno : ENOENT;
		return -1;
	}
	return ret + 5;
}

ssize_t read(int fd, void *buf, size_t count)
{
	if (fd < 5)
		return 0;

	fd -= 5;
	size_t total = 0;
	char *p = (char*)buf;
	while (total < count) {
		size_t chunk = count - total;
		if (chunk > 16384)
			chunk = 16384;
		ssize_t ret = fs_read(fd, p + total, chunk);
		if (ret < 0) {
			if (total > 0)
				return total;
			errno = g_errno ? g_errno : EIO;
			return -1;
		}
		if (ret == 0)
			break;
		total += ret;
		if ((size_t)ret < chunk)
			break;
	}
	return total;
}

ssize_t write(int fd, const void *buf, size_t count)
{
	if (fd <= 0)
		return -1;
	else if (fd == 1 || fd == 2)
	{
		return count;
	}
	else if (fd < 5)
		return -1;

	fd -= 5;
	size_t total = 0;
	const char *p = (const char*)buf;
	while (total < count) {
		size_t chunk = count - total;
		if (chunk > 16384)
			chunk = 16384;
		ssize_t ret = fs_write(fd, p + total, chunk);
		if (ret < 0) {
			if (total > 0)
				return total;
			errno = g_errno ? g_errno : EIO;
			return -1;
		}
		if (ret == 0)
			break;
		total += ret;
		if ((size_t)ret < chunk)
			break;
	}
	return total;
}

off_t lseek(int fd, off_t offset, int whence)
{
	if (fd < 5)
		return -1;

	fd -= 5;
	int64_t ret = fs_lseek(fd, offset, whence);
	if (ret < 0) {
		errno = g_errno ? g_errno : EINVAL;
		return -1;
	}
	return ret;
}

int close(int fd)
{
	if (fd < 5)
		return 0;

	fd -= 5;
	int ret = fs_close(fd);
	if (ret < 0) {
		errno = g_errno;
		return -1;
	}
	return 0;
}

typedef struct {
	union {
		struct {
			uint8_t	_1[0x18];	// type is at offset 0x18
			uint32_t type;		// 0x81b6 - file,	0x41ff - dir
		};
		struct {
			uint8_t	_2[0x38];	// size is at offset 0x38
			uint32_t size;		// filesize if type is a file
		};
		uint8_t	__[160];		// total struct size is 160
	};
} fs_stat_t;

static int stat_common(int ret, fs_stat_t *buffer, struct stat *sbuf)
{
	if (ret == 0)
	{
		memset(sbuf, 0, sizeof(*sbuf));
		sbuf->st_mode = S_ISREG(buffer->type)*S_IFREG | S_ISDIR(buffer->type)*S_IFDIR | (S_IRUSR|S_IWUSR);
		sbuf->st_size = buffer->size;
		return 0;
	}
	else
		return -1;
}

// wrap fs_stat to supply a more standard stat implementation
// for now only `type` (for dir or file) and `size` fields of `struct stat` are filled
int	stat(const char *path, struct stat *sbuf)
{
	char resolved[512];
	const char *p = resolve_path(path, resolved, sizeof(resolved));

	fs_stat_t buffer = {0};
	int ret = fs_stat(p, &buffer);
	return stat_common(ret, &buffer, sbuf);
}

int	fstat(int fd, struct stat *sbuf)
{
	if (fd < 5)
		return -1;
	fd -= 5;
	fs_stat_t buffer = {0};
	int ret = fs_fstat(fd, &buffer);
	return stat_common(ret, &buffer, sbuf);
}

